export interface PixelCell {
  x: number;
  y: number;
  /** Порядок появления 0…1 — псевдослучайный, но стабильный для одного слова. */
  order: number;
}

/** Раскладывает слово в клетки. Между буквами — одна пустая колонка. */
export function layoutPixels(text: string): { cells: PixelCell[]; width: number; height: number } {
  const cells: PixelCell[] = [];
  let x = 0;
  let seed = 7;
  const rand = () => {
    seed = (seed * 9301 + 49297) % 233280;
    return seed / 233280;
  };
  for (const ch of text.toUpperCase()) {
    const g = glyphs[ch] ?? glyphs[' '];
    g.forEach((row, y) => {
      [...row].forEach((c, dx) => {
        if (c === '#') cells.push({ x: x + dx, y, order: rand() });
      });
    });
    x += 6;
  }
  return { cells, width: Math.max(0, x - 1), height: 7 };
}
