/**
 * Типограф для готового HTML: короткие слова не остаются в конце строки, тире не начинает строку.
 * После предлогов, союзов и частиц из списка ставится неразрывный пробел, перед длинным тире — тоже.
 * Работает только с текстом между тегами: атрибуты, script, style, textarea и pre не трогает.
 */

/**
 * Короткое слово (предлог, союз, частица) после пробела, начала текста или открывающего знака,
 * за ним — пробелы и следующее слово.
 */
const SHORT =
  /(?<=^|[\s («„"“—])(а|в|во|и|к|ко|о|об|с|со|у|я|на|по|за|из|от|до|не|ни|но|да|для|без|или|при|под|над|про|что|как)[ \t\n\r]+(?=[^\s<])/giu;
/** Пробел перед тире: тире остаётся в конце строки, а не переносится в начало следующей. */
const DASH = /[ \t\n\r]+([—–])(?=[ \t\n\r])/g;
/**
 * Разбор HTML на три вида кусков: блок, текст которого не трогаем целиком (script, style, textarea,
 * pre — внутри CSS и JS могут встречаться «<» и «>»), отдельный тег и текст между тегами.
 */
const TOKENS = /(<(script|style|textarea|pre)\b[\s\S]*?<\/\2\s*>)|(<[^>]*>)|([^<]+)/gi;

export function typograph(html: string): string {
  return html.replace(TOKENS, (match, _raw, _name, _tag, text: string | undefined) => {
    if (!text || !text.trim()) return match;
    return text.replace(SHORT, '$1 ').replace(DASH, ' $1');
  });
}
